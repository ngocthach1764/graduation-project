#!/usr/bin/env python3
"""Fit the locked per-protocol binary models and export C++ headers."""

import argparse
import json
from pathlib import Path

import pandas as pd

import build_behavior_features as featlib
import train_and_export as trainlib
import tune_hierarchical as hier

# The feature list is spelled out in both modules; keep them from drifting,
# since the exported models index the vector positionally.
if list(trainlib.FEATURES_BEHAVIOR20) != list(featlib.FEATURES_BEHAVIOR20):
    raise SystemExit(
        'FEATURES_BEHAVIOR20 differs between train_and_export.py and '
        'build_behavior_features.py; reconcile them before exporting.')


PROTOCOL_FILE = {
    'DNP3': 'dnp3',
    'IEC104': 'iec104',
    'OPC-UA': 'opcua',
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--csv-train', nargs='+', required=True)
    ap.add_argument('--config-dir', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--families', nargs='+', choices=['dt', 'rf'],
                    default=['dt', 'rf'])
    args = ap.parse_args()

    out_dir = Path(args.out).expanduser().resolve()
    config_dir = Path(args.config_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    trainlib.FEATURES = trainlib.FEATURES_BEHAVIOR20

    frames = [trainlib.load_csv(path, i + 1)
              for i, path in enumerate(args.csv_train)]
    fit_df = trainlib.add_derived_features(
        pd.concat(frames, ignore_index=True))

    exported = {}
    for family in args.families:
        config_path = config_dir / f'binary_per-protocol_{family}_config.json'
        configs = json.loads(config_path.read_text(encoding='utf-8'))
        exported[family] = {}
        for protocol, stem in PROTOCOL_FILE.items():
            config = configs[protocol]
            protocol_df = fit_df[fit_df['protocol'].astype(str) == protocol]
            model = hier.fit_stage(protocol_df, 1, config['model'])
            classes = [str(value) for value in model.classes_]
            if set(classes) != {'NORMAL', 'URGENT'}:
                raise SystemExit(f'{protocol}/{family}: bad classes {classes}')
            urgent_index = classes.index('URGENT')
            fn_name = f'score_binary_{family}_{stem}'
            header_path = out_dir / f'scada_binary_{family}_{stem}.h'
            trainlib.export_model(model, fn_name, header_path, len(classes))
            if family == 'rf':
                # m2cgen gives every forest the same global helper names.
                # Namespace them per exported function so all protocol models
                # can be included in one C++ translation unit.
                code = header_path.read_text(encoding='utf-8')
                code = code.replace(
                    'add_vectors', f'add_vectors_{fn_name}')
                code = code.replace(
                    'mul_vector_number', f'mul_vector_number_{fn_name}')
                header_path.write_text(code, encoding='utf-8')
            exported[family][protocol] = {
                'function': fn_name,
                'urgent_index': urgent_index,
                'threshold': config['threshold']['urgent_threshold'],
                'depth': config['model']['depth'],
                'trees': config['model']['trees'],
                'leaf': config['model']['leaf'],
            }

    config_lines = [
        '#pragma once',
        '',
        '// AUTO-GENERATED by ml/export_binary_models.py.',
        'namespace scada_binary_config {',
    ]
    for family, family_models in exported.items():
        for protocol, values in family_models.items():
            stem = PROTOCOL_FILE[protocol].upper()
            prefix = f'{family.upper()}_{stem}'
            config_lines.append(
                f'inline constexpr int {prefix}_URGENT_INDEX = '
                f'{values["urgent_index"]};')
            config_lines.append(
                f'inline constexpr double {prefix}_THRESHOLD = '
                f'{values["threshold"]:.17g};')
    config_lines.extend(['}', ''])
    (out_dir / 'scada_binary_config.h').write_text(
        '\n'.join(config_lines), encoding='utf-8')

    # The exported scorers index their feature array positionally, so the
    # runtime vector must be built in exactly this order.  Emit the order as a
    # header that ml_inference.cc static_asserts against, turning a feature
    # reorder into a build failure instead of silent misprediction.
    features = list(trainlib.FEATURES_BEHAVIOR20)
    feature_lines = [
        '#pragma once',
        '',
        '// AUTO-GENERATED by ml/export_binary_models.py.',
        '// Feature order the exported models in this directory were trained on.',
        '// ml_inference.cc static_asserts its runtime layout against this list.',
        '#include <string_view>',
        '',
        'namespace scada_binary_config {',
        f'inline constexpr int TRAINED_N_FEATURES = {len(features)};',
        'inline constexpr std::string_view '
        'TRAINED_FEATURE_NAMES[TRAINED_N_FEATURES] = {',
    ]
    feature_lines.extend(f'    "{name}",' for name in features)
    feature_lines.extend(['};', '}', ''])
    (out_dir / 'scada_binary_features.h').write_text(
        '\n'.join(feature_lines), encoding='utf-8')

    manifest = {'feature_names': features, 'models': exported}
    (out_dir / 'scada_binary_manifest.json').write_text(
        json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'Exported binary models to {out_dir}')


if __name__ == '__main__':
    main()
